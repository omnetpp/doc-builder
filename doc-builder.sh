#!/usr/bin/env bash
#
# Builds the documentation site of an OMNeT++ model project in the doc-builder image
# (ghcr.io/omnetpp/doc-builder): the NED reference with opp_docgen, optionally a Sphinx site around it,
# and optionally the C++ API with doxygen. action.yml runs it; it also runs locally from the project
# root. See README.md and --help.
#
# Env:  ENGINE  podman, docker, or none to build without a container (default: none inside a
#               container, otherwise podman if installed, otherwise docker)
#
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
    cat <<'EOF'
Usage: doc-builder.sh [options]

Builds a documentation site in the doc-builder image. Paths are relative to the current directory,
which must contain all of them (it is mounted into the container).

Without --sphinx-source, the site is the NED reference generated by opp_docgen. With it, the NED
reference is generated as reStructuredText into the Sphinx project, which is then built.

  --project-dir DIR       the OMNeT++ project whose NED and MSG files are documented (default: .)
  --output-dir DIR        where the site is built (default: _site)
  --title TEXT            title of the NED reference and the C++ API (default: name of the project dir)
  --sphinx-source DIR     the Sphinx project (with conf.py) to build the site from
  --ned-dir DIR           where the NED reference goes in the Sphinx project (default: ned)
  --ned-format FORMAT     opp_docgen format without Sphinx: html-material (default), html-readthedocs
                          or html
  --ned-path PATHS        NED source roots of dependencies, ';'- or ':'-separated, indexed for linking
                          but not documented
  --external-docs LIST    documentation of dependencies to link to: <package>=<url> items, comma- or
                          space-separated (opp_docgen -l)
  --docgen-args ARGS      further opp_docgen arguments (split at whitespace)
  --doxygen               also generate the C++ API with doxygen
  --doxygen-input PATHS   source directories for the bundled doxygen configuration (default:
                          <project-dir>/src)
  --doxyfile FILE         own doxygen configuration instead of the bundled one
  --api-dir DIR           where the C++ API goes, in the Sphinx project or the site (default: api)
  --pdf                   also build the Sphinx project as PDF (latexpdf)
  --sphinx-args ARGS      further sphinx-build arguments (split at whitespace)
  --fail-on-warnings      fail if opp_docgen or Sphinx warn
  --image-tag TAG         tag of ghcr.io/omnetpp/doc-builder (default: latest)
  --image REF             image to use instead, as is
  -h, --help              show this help

Boolean options also take a value: --pdf=true, --pdf=false.
EOF
}

die() {
    echo "doc-builder: error: $*" >&2
    exit 1
}

project_dir=.
output_dir=_site
title=
sphinx_source=
ned_dir=ned
ned_format=html-material
ned_path=
external_docs=
docgen_args=
doxygen=false
doxygen_input=
doxyfile=
api_dir=api
pdf=false
sphinx_args=
fail_on_warnings=false
image_tag=latest
image=

set_bool() {
    case "$2" in
        true|false) printf -v "$1" %s "$2" ;;
        *) die "--${1//_/-} takes true or false, not '$2'" ;;
    esac
}

set_option() {
    case "$1" in
        project-dir|output-dir|title|sphinx-source|ned-dir|ned-format|ned-path|external-docs|docgen-args| \
        doxygen-input|doxyfile|api-dir|sphinx-args|image-tag|image)
            printf -v "${1//-/_}" %s "$2" ;;
        doxygen|pdf|fail-on-warnings)
            set_bool "${1//-/_}" "$2" ;;
        *) die "unknown option --$1 (see --help)" ;;
    esac
}

args=("$@")
while [ $# -gt 0 ]; do
    arg="$1"
    shift
    case "$arg" in
        -h|--help) usage; exit 0 ;;
        --doxygen|--pdf|--fail-on-warnings) set_option "${arg#--}" true ;;
        --*=*) name="${arg%%=*}"; set_option "${name#--}" "${arg#*=}" ;;
        --*) [ $# -gt 0 ] || die "$arg needs a value"; set_option "${arg#--}" "$1"; shift ;;
        *) die "unexpected argument '$arg' (see --help)" ;;
    esac
done

if [ -z "$sphinx_source" ]; then
    case "$ned_format" in html-material|html-readthedocs|html) ;; *) die "unknown --ned-format '$ned_format'" ;; esac
    [ "$pdf" = false ] || die "--pdf needs --sphinx-source: opp_docgen writes no PDF"
fi
[ -n "$image" ] || image="ghcr.io/omnetpp/doc-builder:$image_tag"

if [ -z "${ENGINE:-}" ]; then
    if [ -f /.dockerenv ] || [ -f /run/.containerenv ]; then ENGINE=none
    elif command -v podman >/dev/null; then ENGINE=podman
    else ENGINE=docker
    fi
fi

# Outside the image: run this script again in it. Paths are mounted at the same location, so that
# they mean the same inside.
if [ "$ENGINE" != none ] && [ -z "${DOC_BUILDER_IN_CONTAINER:-}" ]; then
    root="$(pwd -P)"
    mounts=(-v "$root:$root")
    # The action runs from a checkout of its own repository, which can be the project (its own tests)
    case "$HERE/" in
        "$root"/*) ;;
        *) mounts+=(-v "$HERE:$HERE:ro") ;;
    esac
    out="$(realpath -m "$output_dir")"
    case "$out/" in
        "$root"/*) ;;
        *) mkdir -p "$out"; mounts+=(-v "$out:$out") ;;
    esac
    # A rootless engine maps the container's root to the calling user; a rootful one (docker on GitHub's
    # runners) needs to be told the user, or the output would belong to root.
    user=(--security-opt label=disable)
    if ! "$ENGINE" info 2>/dev/null | grep -Eqi 'name=rootless|rootless: true'; then
        user+=(--user "$(id -u):$(id -g)")
    fi
    echo "doc-builder: running in $image with $ENGINE"
    exec "$ENGINE" run --rm --init --platform linux/amd64 "${user[@]}" "${mounts[@]}" \
        -e HOME=/tmp -e DOC_BUILDER_IN_CONTAINER=1 -w "$root" \
        "$image" bash "$HERE/doc-builder.sh" "${args[@]}"
fi

for tool in opp_docgen sphinx-build doxygen doxysphinx; do
    command -v "$tool" >/dev/null || die "$tool not found; run in the doc-builder image (ENGINE=podman or docker)"
done

# Directories that the build generates are emptied first; one that has content but was not made by
# doc-builder (no marker file) is left alone, so that a wrong path does not delete anything.
MARKER=.doc-builder
prepare_dir() {
    if [ -d "$1" ] && [ -n "$(ls -A "$1")" ] && [ ! -e "$1/$MARKER" ]; then
        die "$1 is not empty and was not generated by doc-builder; refusing to overwrite it"
    fi
    mkdir -p "$1"
    find "$1" -mindepth 1 -delete
    touch "$1/$MARKER"
}

warnings=0

# opp_docgen exits with 1 if it warned, 2 if it failed.
docgen() {
    local status=0
    opp_docgen "$@" || status=$?
    case "$status" in
        0) ;;
        1) warnings=1
           [ "$fail_on_warnings" = false ] || die "opp_docgen warned (fail-on-warnings is set)" ;;
        *) die "opp_docgen failed" ;;
    esac
}

project="$(realpath "$project_dir")"
out="$(realpath -m "$output_dir")"
name="${title:-$(basename "$project")}"
docgen_opts=()
[ -z "$title" ] || docgen_opts+=(--title="$title")
[ -z "$ned_path" ] || docgen_opts+=(--ned-path="$ned_path")
[ -z "$external_docs" ] || docgen_opts+=(-l "$external_docs")
read -r -a extra <<< "$docgen_args"
docgen_opts+=("${extra[@]}")

# The settings after the configuration are the ones the build relies on; in doxygen, the last one wins.
run_doxygen() {
    local dir="$1" sphinx="$2"
    {
        if [ -n "$doxyfile" ]; then
            cat "$doxyfile"
        else
            cat "$HERE/doxygen/Doxyfile"
            echo "INPUT = ${doxygen_input:-$project_dir/src}"
            echo "PROJECT_NAME = \"$name\""
        fi
        echo "OUTPUT_DIRECTORY = $dir"
        echo "HTML_OUTPUT = ."
        echo "GENERATE_HTML = YES"
        echo "HTML_FILE_EXTENSION = .html"
        echo "CREATE_SUBDIRS = NO"
        echo "GENERATE_TAGFILE = $dir/tagfile.xml"
        if [ "$sphinx" = true ]; then
            # what doxysphinx needs
            echo "GENERATE_TREEVIEW = NO"
            echo "DISABLE_INDEX = NO"
            echo "SEARCHENGINE = NO"
            echo "HTML_EXTRA_STYLESHEET += $HERE/doxygen/sphinx.css"
        fi
    } | DOC_BUILDER_ACTION_DIR="$HERE" doxygen - || die "doxygen failed"
}

# Links from the type pages of the NED reference to the classes of the C++ API.
doxytags_opts() {
    local types_dir="$1" api="$2"
    echo "--doxytags=$api/tagfile.xml"
    echo "--doxy-url-prefix=$(realpath -m --relative-to="$types_dir" "$api")/"
}

# The index of the C++ API in the Sphinx project: the class list, and all pages of the API in its
# (hidden) toctree, so that Sphinx does not warn about pages outside every toctree.
write_api_index() {
    local dir="$1" pages=() page
    local patterns=(hierarchy 'namespace*' 'class*' 'struct*' 'union*' 'group_*' '*_8h' '*_source' '*')
    declare -A seen=()
    for pattern in "${patterns[@]}"; do
        for page in "$dir"/$pattern.rst; do
            [ -e "$page" ] || continue
            page="$(basename "$page" .rst)"
            [ -z "${seen[$page]:-}" ] || continue
            seen[$page]=1
            pages+=("$page")
        done
    done
    {
        printf '%s\n' "$name C++ API" "$(printf '%*s' "$(( ${#name} + 8 ))" '' | tr ' ' '=')" "" \
            ".. toctree::" "   :hidden:" ""
        printf '   %s\n' "${pages[@]}"
        if [ -f "$dir/annotated.html" ]; then
            printf '%s\n' "" ".. container:: doxygen-content" "" "   .. raw:: html" "      :file: annotated.html"
        fi
    } > "$dir/index.rst"
}

if [ -z "$sphinx_source" ]; then
    prepare_dir "$out"
    doxy=()
    if [ "$doxygen" = true ]; then
        run_doxygen "$out/$api_dir" false
        types_dir="$out/types"
        [ "$ned_format" != html-material ] || types_dir="$out"
        mapfile -t doxy < <(doxytags_opts "$types_dir" "$out/$api_dir")
    fi
    docgen --format="$ned_format" -o "$out" "${doxy[@]}" "${docgen_opts[@]}" "$project"
else
    src="$(realpath "$sphinx_source")"
    [ -f "$src/conf.py" ] || die "no conf.py in $sphinx_source"
    ned_out="$src/$ned_dir"
    api_out="$src/$api_dir"
    prepare_dir "$ned_out"
    doxy=()
    if [ "$doxygen" = true ]; then
        prepare_dir "$api_out"
        run_doxygen "$api_out" true
        mapfile -t doxy < <(doxytags_opts "$ned_out/types" "$api_out")
    fi
    docgen --format=rst -o "$ned_out" "${doxy[@]}" "${docgen_opts[@]}" "$project"

    prepare_dir "$out"
    if [ "$doxygen" = true ]; then
        # The same pruning as in the OMNeT++ API documentation: no member lists and pages index.
        (cd "$api_out" && rm -f pages.html files.html ./*-members.html functions*.html)
        doxysphinx build --doxygen_exe doxygen "$src" "$out" "$api_out" || die "doxysphinx failed"
        (cd "$api_out" && rm -f index.rst graph_legend.rst annotated.rst files.rst annotated_classes.rst \
            topics.rst dir_*.rst ./*-members.rst deprecated.rst && sed -i 's/:orphan://' ./*.rst)
        write_api_index "$api_out"
    fi

    work="$(mktemp -d)"
    sphinx_opts=(-d "$work/doctrees")
    [ "$fail_on_warnings" = false ] || sphinx_opts+=(-W --keep-going)
    read -r -a extra <<< "$sphinx_args"
    sphinx_opts+=("${extra[@]}")
    # From the Sphinx project, so that relative paths in conf.py that Sphinx does not resolve itself
    # (e.g. the tag files of doxylink) mean the same as in a plain `sphinx-build .` there.
    cd "$src"
    sphinx-build -b html "${sphinx_opts[@]}" . "$out" || die "sphinx-build failed"
    if [ "$pdf" = true ]; then
        sphinx-build -M latexpdf . "$work/pdf" "${sphinx_opts[@]}" || die "sphinx-build latexpdf failed"
        cp "$work/pdf/latex/"*.pdf "$out/"
    fi
    rm -rf "$work"
fi

echo "doc-builder: built $out"
[ "$warnings" = 0 ] || echo "doc-builder: opp_docgen reported warnings"
